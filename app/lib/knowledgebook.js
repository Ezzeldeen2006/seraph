// The AQW knowledge book: vault notes the AI Brain reads before answering (<notes>\KNOWLEDGE), generated from
// Seraph's own data (progression goals, ultra comps + enhancement presets, leveling routes, dailies, boosts calendar, the
// AQW Hub class guide, the Skua script index), plus hand-written notes like AQW-Basics. The whole vault is then indexed
// into the local knowledge base "aqw" (<ai>\knowledge\aqw) so the AI can search it by meaning.
const fs = require('fs');
const path = require('path');
const { P } = require('./paths');
const { readJson } = require('./util');
const progression = require('./progression');
const knowledge = require('./knowledge');
const personas = require('./personas');
let kb = null;
try { kb = require(require('path').join(process.env.SERAPH_AI_CORE || 'seraph-ai-core', 'knowledge')); } catch (e) { kb = null; }

const DIR = () => path.join(P.VAULT, 'KNOWLEDGE');
const stamp = () => `_Generated by Seraph ${new Date().toISOString().slice(0, 10)}. Don't edit by hand; it's rewritten._`;

function write(name, body) {
  fs.mkdirSync(DIR(), { recursive: true });
  fs.writeFileSync(path.join(DIR(), `${name}.md`), body);
}

function generate(hub) {
  const goals = Object.entries(progression.GOALS);
  write('Progression-Goals', [`# Progression goals (what to farm, in which order)`, '', stamp(), '',
    '| id | Goal | From level | Everyone needs it | Farmed by (Skua script) | Why |', '|---|---|---|---|---|---|',
    ...goals.map(([id, g]) => `| ${id} | ${g.label} | ${g.when} | ${g.must ? 'yes' : ''}${g.needsAc ? ` (needs ${g.needsAc} AC)` : ''} | ${g.script} | ${g.purpose || ''} |`),
    '', '## Character specialties', '',
    ...Object.values(personas.PERSONAS).map((p) => `- **${p.name}** (${p.id}, ${p.archetype}): ultra slot ${p.ultraClass}; path ${p.path.map((id) => (progression.GOALS[id] || {}).label || id).join(' → ')}.`),
    '', 'Rules: own specialty first; other characters\' must-haves unlock at level 80, extras at 90. Seraph starts goals by itself.'].join('\n'));

  let enh = {};
  try { enh = require('./ultra-enhancements.json'); } catch (e) { enh = {}; }
  write('Ultras', [`# Ultra bosses: classes and enhancements`, '', stamp(), '',
    '| Map | Boss | Cadence | Classes (taunt slots, Skua v3) |', '|---|---|---|---|',
    ...Object.entries(progression.ULTRAS).map(([id, u]) => `| /${id} | ${u.label} | ${u.cadence} | ${u.classes.join(', ')} |`),
    '', '## Enhancement presets per boss (class: type · weapon · helm · cape)', '',
    ...Object.entries(enh).map(([boss, table]) => `### ${boss}\n${Object.entries(table).map(([cls, p]) => `- ${cls}: ${p.type} · ${p.weapon || '-'}${p.weaponFallback ? ` (or ${p.weaponFallback})` : ''} · ${p.helm || '-'} · ${p.cape || '-'}`).join('\n')}`)].join('\n'));

  let routes = [];
  try { routes = require('./bot').LEVEL_ROUTES; } catch (e) { routes = []; }
  write('Leveling', [`# Leveling routes`, '', stamp(), '',
    '| Below level | Map | Cell | Monster |', '|---|---|---|---|',
    ...routes.map((r) => `| ${r.below} | /${r.map} | ${r.cell} | ${r.monster} |`),
    '', 'Community guide (AQW Progression Guide): 1–25 do the 13 Lords of Chaos story; 25–50 /underlair room 5 Void Draconians or /fireplanewar war medals; 50–75 /sevencircleswar room 2; 75–100 /icestormarena Icy Winds. Always level on 2x XP days.'].join('\n'));

  try {
    const d = knowledge.dailies();
    write('Dailies', [`# Dailies Seraph knows (from Skua CoreDailies)`, '', stamp(), '',
      '| Daily | F2P runnable | Member only | Min level |', '|---|---|---|---|',
      ...d.map((x) => `| ${x.name} | ${x.runnable ? 'yes' : 'no'} | ${x.memberOnly ? 'yes' : ''} | ${x.minLevel || ''} |`), '', 'Dailies reset at midnight EST.'].join('\n'));
  } catch (e) { /* knowledge not generated yet */ }

  if (hub && hub.boosts) {
    const s = hub.boosts.summary();
    write('Boosts-Calendar', [`# Boosts & events (Artix calendar)`, '', stamp(), '',
      `**Active today:** ${s.active.map((b) => b.title).join(', ') || 'none'}`, '',
      '## Next 7 days', ...s.upcoming.map((u) => `- ${u.date}: ${u.title}`), '',
      '## Recent events', ...s.recentEvents.map((e) => `- ${e}`), '',
      'Scheduled boosts run one server day from 12:01 AM EST. See [[AQW-Basics]] for what to do on each boost.'].join('\n'));
  }

  const guide = path.join(P.KNOWLEDGE, 'aqwhub-class-guide.txt');
  if (fs.existsSync(guide)) write('Classes-Guide', `# Classes guide (AQW Hub)\n\n${fs.readFileSync(guide, 'utf8')}`);

  const scripts = readJson(path.join(P.SCRIPTS, 'scripts.json'), []);
  if (Array.isArray(scripts) && scripts.length) {
    write('Skua-Scripts-Index', [`# Skua scripts index (${scripts.length})`, '', stamp(), '', 'Any path can be queued as a script task.', '',
      ...scripts.map((s) => `- ${s.path || s.filePath} — ${s.name || ''}${s.description && s.description !== 'null' ? `: ${String(s.description).slice(0, 140)}` : ''}`)].join('\n'));
  }
  return fs.readdirSync(DIR());
}

// Generate notes, then (re)index the vault into the "aqw" knowledge base. Incremental: only changed files re-embed.
async function rebuild(hub, log) {
  log = log || (() => {});
  const files = generate(hub);
  if (!kb) { log('knowledge book: <ai>\\core missing, notes written but not indexed'); return { notes: files.length, indexed: false }; }
  const r = await kb.build('aqw', [P.VAULT], (m) => log(`knowledge book: ${m}`));
  return { notes: files.length, indexed: true, ...r };
}

async function search(query, k = 5) {
  if (!kb || !kb.load('aqw')) return [];
  return kb.search('aqw', query, k);
}

module.exports = { generate, rebuild, search };
